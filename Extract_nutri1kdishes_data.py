from google.cloud import storage
import os

client = storage.Client.create_anonymous_client()
bucket = client.bucket('nutrition5k_dataset')

# Adjust prefix based on the folder structure
blobs = bucket.list_blobs(prefix='nutrition5k_dataset/imagery/realsense_overhead/')

count = 0
for blob in blobs:
    if count >= 1000: break

    # We only want the RGB files
    if blob.name.endswith('rgb.png'):
        filename = os.path.join("my_images", blob.name.split('/')[-2] + ".png")
        os.makedirs(os.path.dirname(filename), exist_ok=True)
        blob.download_to_filename(filename)
        count += 1
        print(f"Downloaded {count}/1000")

