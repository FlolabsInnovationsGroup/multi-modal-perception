# 3. Identify your downloaded images
print("\nStep 3: Indexing local images...")
image_folder = 'my_images' # Ensure this matches your folder name
downloaded_ids = [os.path.splitext(f)[0] for f in os.listdir(image_folder) if f.endswith(('.png', '.jpg'))]
print(f"Found {len(downloaded_ids)} images in /{image_folder}")

# 4. Merge and Filter Metadata
print("\nStep 4: Processing metadata and matching IDs...")
# Load both CSVs and combine them
cols = ['dish_id', 'calories', 'mass', 'fat', 'carb', 'protein']
df1 = pd.read_csv('dish_metadata_cafe1.csv', header=None, usecols=[0,1,2,3,4,5], names=cols)
df2 = pd.read_csv('dish_metadata_cafe2.csv', header=None, usecols=[0,1,2,3,4,5], names=cols)

full_metadata = pd.concat([df1, df2]).drop_duplicates(subset='dish_id')

# Filter for only the 1,000 images you have
filtered_metadata = full_metadata[full_metadata['dish_id'].isin(downloaded_ids)]

# 5. Export to JSON
print("\nStep 5: Exporting to JSON...")
nutrition_dict = filtered_metadata.set_index('dish_id').to_dict(orient='index')

with open('nutrition_labels_1000.json', 'w') as f:
    json.dump(nutrition_dict, f, indent=4)

